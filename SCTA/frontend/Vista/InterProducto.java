    /**
     * Lógica principal para validar y salvar el producto en la base de datos.
     */
    private void guardarProducto() {
        // 1. Mostrar ventana de confirmación antes de cualquier proceso
        int respuesta = JOptionPane.showConfirmDialog(this,
                "¿Estás seguro de que deseas guardar este nuevo producto?",
                "Confirmar Registro",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        // 2. Si el usuario selecciona "SÍ" (YES_OPTION), procedemos con la lógica
        if (respuesta == JOptionPane.YES_OPTION) {

            Producto producto = new Producto();
            Ctrl_Producto controlProducto = new Ctrl_Producto();

            String iva = jComboBox_IVA.getSelectedItem().toString().trim();
            String categoria = jComboBox_categoria.getSelectedItem().toString().trim();
            String proveedor = jComboBox_proveedor.getSelectedItem().toString().trim();

            // VALIDACIÓN DE CAMPOS VACÍOS
            if (jTextField_nombre.getText().equals("") || jTextField_descripcion.getText().equals("") || jTextField_precio.getText().equals("")) {
                JOptionPane.showMessageDialog(this, "Complete todos los campos.", "Error.", JOptionPane.ERROR_MESSAGE);
            } else {
                // VALIDACIÓN DE DUPLICADOS
                if (!controlProducto.existeProducto(jTextField_nombre.getText().trim())) {

                    // VALIDACIÓN DE SELECCIÓN EN COMBOS
                    if (iva.equalsIgnoreCase("Seleccione IVA:")
                            || categoria.equalsIgnoreCase("Seleccione Categoría:")
                            || proveedor.equalsIgnoreCase("Seleccione Proveedor:")) {

                        JOptionPane.showMessageDialog(this, "Asegúrese de seleccionar IVA, Categoría y Proveedor.");
                    } else {
                        try {
                            // PREPARACIÓN DEL OBJETO
                            producto.setNombre(jTextField_nombre.getText().trim());
                            producto.setDescripcion(jTextField_descripcion.getText().trim());

                            String precioTXT = jTextField_precio.getText().trim().replace(",", ".");
                            producto.setPrecio_unitario(Double.parseDouble(precioTXT));

                            if (iva.equalsIgnoreCase("No Graba IVA")) {
                                producto.setIVA(0);
                            } else if (iva.equalsIgnoreCase("16% IVA")) {
                                producto.setIVA(16);
                            }

                            this.idCategoria();
                            producto.setIdCategoria(obtenerIdCategoriaCombo);
                            this.idProveedor();
                            producto.setIdProveedor(obtenerIdProveedorCombo);

                            // EJECUCIÓN DE LA GUARDA
                            if (controlProducto.guardar(producto)) {
                                JOptionPane.showMessageDialog(this, "Producto Guardado Exitosamente.");
                                this.limpiar();
                                this.cargarCategorias();
                                this.cargarProveedores();
                            } else {
                                JOptionPane.showMessageDialog(this, "Error interno al guardar en la base de datos.");
                            }
                        } catch (HeadlessException | NumberFormatException e) {
                            JOptionPane.showMessageDialog(this, "Error de formato en precio: " + e);
                        }
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "El producto ya existe en el sistema.");
                }
            }
        } else {
            // Opcional: Mensaje o acción si el usuario cancela
            System.out.println("Inserción cancelada por el usuario.");
        }
    }

