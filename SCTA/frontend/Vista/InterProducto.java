    /**
     * OBTENCIÓN DE ID POR NOMBRE Convierte el texto seleccionado en el Combo al
     * ID (int) de la BD
     */
    private int idCategoria() {
        String sql = "select * from categoria where descripcion = '" + this.jComboBox_categoria.getSelectedItem() + "'";
        Statement st;

        try {
            Connection cn = Conexión.conectar();
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            while (rs.next()) {
                obtenerIdCategoriaCombo = rs.getInt("id_categoria");
            }
            cn.close();
        } catch (SQLException e) {
            System.out.println("Error al obtener idCategoria.");
        }

        return obtenerIdCategoriaCombo;
    }

