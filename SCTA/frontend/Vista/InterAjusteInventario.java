    /**
     * ACCIÓN: Actualizar (Botón Verde) Envía los nuevos valores del JSpinner al
     * controlador para impactar la DB.
     */
    private void jButton_actualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_actualizarActionPerformed
        // TODO add your handling code here:

        // 1. Validar que se haya seleccionado un producto
        if (idProducto == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto de la tabla primero.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Mostrar pestaña de confirmación
        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de que desea actualizar el stock de este producto?",
                "Confirmar Actualización",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE
        );

        // 3. Si el administrador selecciona "SÍ", se procede con la actualización
        if (respuesta == JOptionPane.YES_OPTION) {
            Producto producto = new Producto();
            Ctrl_Producto controlProducto = new Ctrl_Producto();

            try {
                producto.setStock_actual((int) jSpinner_stockactual.getValue());
                producto.setStock_minimo((int) jSpinner_stockminimo.getValue());

                if (controlProducto.actualizarAjusteInventario(producto, idProducto)) {
                    JOptionPane.showMessageDialog(this, "Producto Actualizado correctamente.", "Operación Exitosa", JOptionPane.INFORMATION_MESSAGE);
                    this.organizarPorCategorias();

                    // Limpiar selección para evitar actualizaciones duplicadas accidentales
                    idProducto = 0;
                    jSpinner_stockactual.setValue(0);
                    jSpinner_stockminimo.setValue(0);

                } else {
                    JOptionPane.showMessageDialog(this, "Error al actualizar en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (HeadlessException | NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Error de formato: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        // Si selecciona "NO", el método termina y no pasa nada.


    }//GEN-LAST:event_jButton_actualizarActionPerformed

