    /**
     * FILTRADO POR TEXTO (Buscador) Se ejecuta en el evento keyReleased: cada
     * vez que el usuario suelta una tecla.
     */
    private void txt_buscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_buscarKeyReleased
        // TODO add your handling code here:

        String texto = txt_buscar.getText().trim();

        if (texto.length() == 0) {
            sorter.setRowFilter(null);
        } else {
            // Filtra sin importar mayúsculas/minúsculas (?i)
            // El índice 1 corresponde a la columna "Nombre"
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + texto, 1));
        }

    }//GEN-LAST:event_txt_buscarKeyReleased

    private void txt_buscarKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txt_buscarKeyTyped
        // TODO add your handling code here:

        // 1. Obtenemos el carácter presionado
        char car = evt.getKeyChar();

        // 2. Validamos si NO es letra, NO es dígito, NO es espacio, NO es punto y NO es coma
        if (!Character.isLetter(car) && !Character.isDigit(car) && car != ' ' && car != '.' && car != ',') {

            // 3. Si no cumple con ninguna de las anteriores, se "consume" el evento
            evt.consume();
        }

    }//GEN-LAST:event_txt_buscarKeyTyped


