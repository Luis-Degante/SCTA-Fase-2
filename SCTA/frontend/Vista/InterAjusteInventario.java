    private void organizarPorCategorias() {
        // Limpiar filas actuales sin borrar columnas
        modeloInventario.setRowCount(0);

        String seleccion = jComboBox_categorias.getSelectedItem().toString();
        String sql = "SELECT p.id_producto, p.nombre, c.descripcion, prov.nombre, p.stock_actual, p.stock_minimo "
                + "FROM producto p "
                + "INNER JOIN categoria c ON p.id_categoria = c.id_categoria "
                + "INNER JOIN proveedor prov ON p.id_proveedor = prov.id_proveedor ";

        if (!seleccion.equals("Todos")) {
            sql += "WHERE c.descripcion = ?";
        }

        try (Connection cn = Conexión.conectar(); PreparedStatement pst = cn.prepareStatement(sql)) {

            if (!seleccion.equals("Todos")) {
                pst.setString(1, seleccion);
            }

            ResultSet rs = pst.executeQuery();
            while (rs.next()) {
                Object fila[] = {rs.getInt(1), rs.getString(2), rs.getString(3),
                    rs.getString(4), rs.getInt(5), rs.getInt(6)};
                modeloInventario.addRow(fila);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al cargar datos: " + e);
        }
    }

    /**
     * CARGA DE DATOS AL SELECCIONAR Consulta el stock actual y mínimo
     * directamente de la DB para asegurar datos frescos.
     */
    private void EnviarDatosProductoSeleccionado(int idProducto) {

        String sql = "select stock_actual, stock_minimo from producto where id_producto = ?";

        try {
            Connection con = Conexión.conectar();
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, idProducto);
            ResultSet rs = pst.executeQuery();

            if (rs.next()) {

                jSpinner_stockactual.setValue(rs.getInt("stock_actual"));
                jSpinner_stockminimo.setValue(rs.getInt("stock_minimo"));

            }
            con.close();
        } catch (SQLException e) {
            System.err.println("Error al obtener datos del producto: " + e);
        }
    }

    //Metodo que carga las categorias en el JComboBox
    private void cargarCategorias() {
        Connection cn = Conexión.conectar();
        String sql = "select * from categoria";
        Statement st;

        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            jComboBox_categorias.removeAllItems();
            jComboBox_categorias.addItem("Todos");

            while (rs.next()) {

                jComboBox_categorias.addItem(rs.getString("descripcion"));
            }

            cn.close();

        } catch (SQLException e) {
        }

    }

