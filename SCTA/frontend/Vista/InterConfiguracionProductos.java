    /**
     * Lógica del botón ACTUALIZAR: Valida campos y envía el objeto Producto al
     * controlador.
     */
    private void jButton_actualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_actualizarActionPerformed
        // TODO add your handling code here:

        if (idProducto == 0) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione un producto de la tabla primero.");
            return;
        }

        Producto producto = new Producto();
        Ctrl_Producto controlProducto = new Ctrl_Producto();
        String categoria = jComboBox_categoria.getSelectedItem().toString().trim();
        String proveedor = jComboBox_proveedor.getSelectedItem().toString().trim();

        // Validación de campos vacíos
        if (txt_nombre.getText().isEmpty() || txt_descripcion.getText().isEmpty() || txt_puntos.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            // Validación de ComboBoxes
            if (categoria.equalsIgnoreCase("Seleccione Categoría:")) {
                JOptionPane.showMessageDialog(this, "Seleccione una categoria.");
            } else {
                int confirmacion = JOptionPane.showConfirmDialog(this, "¿Desea actualizar?", "Confirmar", JOptionPane.YES_NO_OPTION);
                if (confirmacion == JOptionPane.YES_OPTION) {
                    try {
                        producto.setNombre(txt_nombre.getText().trim());
                        producto.setDescripcion(txt_descripcion.getText().trim());

                        // Obtenemos los IDs numéricos de las llaves foráneas antes de guardar
                        producto.setIdCategoria(this.idCategoria());
                        producto.setIdProveedor(this.idProveedor());
                        producto.setPuntos_otorgados(Integer.parseInt(txt_puntos.getText().trim()));

                        if (controlProducto.actualizarConfiguracion(producto, idProducto)) {
                            JOptionPane.showMessageDialog(this, "Producto Actualizado.");
                            this.organizarPorCategorias(); // Refresca la tabla
                            this.limpiar(); // Limpia el formulario
                        }
                    } catch (Exception e) {
                        JOptionPane.showMessageDialog(this, "Error: " + e);
                    }
                }
            }
        }
    }//GEN-LAST:event_jButton_actualizarActionPerformed

    /**
     * Lógica del botón ELIMINAR: Borra el registro seleccionado tras confirmación.
     */
    private void jButton_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton_eliminarActionPerformed
        // TODO add your handling code here:

        Ctrl_Producto controlProducto = new Ctrl_Producto();

        if (idProducto == 0) {
            JOptionPane.showMessageDialog(null, "Seleccione un producto de la tabla.");
        } else {
            // Añadiendo el cuadro de confirmación
            int confirmacion = JOptionPane.showConfirmDialog(null, "¿Está seguro de eliminar este producto?", "Confirmar Eliminación", JOptionPane.YES_NO_OPTION);

            if (confirmacion == JOptionPane.YES_OPTION) {
                if (controlProducto.EliminarConfiguracion(idProducto)) {
                    JOptionPane.showMessageDialog(null, "¡Producto Eliminado correctamente!");

                    this.organizarPorCategorias();
                    this.cargarCategorias();
                    this.cargarProveedores();
                    this.limpiar();

                    idProducto = 0;
                } else {
                    JOptionPane.showMessageDialog(null, "Error al eliminar el producto.");
                }
            }
        }

    }//GEN-LAST:event_jButton_eliminarActionPerformed

