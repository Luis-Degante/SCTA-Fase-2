    /**
     * FILTRADO POR CATEGORÍA: Reconstruye el contenido de la tabla basado en el JComboBox superior.
     */
    private void organizarPorCategorias() {
        String seleccion = jComboBox_categorias.getSelectedItem().toString();
        model.setRowCount(0); // Limpiar sin recrear el modelo

        String sql = "SELECT p.id_producto, p.nombre, p.descripcion, "
                + "c.descripcion AS categoria, prov.nombre AS proveedor, p.puntos_otorgados "
                + "FROM producto p "
                + "INNER JOIN categoria c ON p.id_categoria = c.id_categoria "
                + "INNER JOIN proveedor prov ON p.id_proveedor = prov.id_proveedor "
                + (seleccion.equals("Todos") ? "" : " WHERE c.descripcion = ?");

        try (Connection cn = Conexión.conectar(); PreparedStatement pst = cn.prepareStatement(sql)) {

            if (!seleccion.equals("Todos")) {
                pst.setString(1, seleccion);
            }

            try (ResultSet rs = pst.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt(1), rs.getString(2), rs.getString(3),
                        rs.getString(4), rs.getString(5), rs.getInt(6)
                    });
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al filtrar: " + e);
        }
    }

