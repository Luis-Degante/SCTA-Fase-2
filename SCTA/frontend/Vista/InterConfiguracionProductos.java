    /**
     * CARGA DE DATOS: Obtiene las categorías de la BD para llenar los ComboBox.
     */
    private void cargarCategorias() {
        Connection cn = Conexión.conectar();
        String sql = "select * from categoria";
        Statement st;

        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBox_categoria.removeAllItems();
            jComboBox_categoria.addItem("Seleccione Categoria:");
            jComboBox_categorias.removeAllItems();
            jComboBox_categorias.addItem("Todos");

            while (rs.next()) {
                jComboBox_categoria.addItem(rs.getString("descripcion"));
                jComboBox_categorias.addItem(rs.getString("descripcion"));
            }

            cn.close();

        } catch (SQLException e) {
        }

    }

        /**
     * CARGA DE DATOS: Obtiene los proveedores de la BD para llenar los ComboBox.
     */
    private void cargarProveedores() {
        Connection cn = Conexión.conectar();
        String sql = "select * from proveedor";
        Statement st;

        try {
            st = cn.createStatement();
            ResultSet rs = st.executeQuery(sql);
            jComboBox_proveedor.removeAllItems();
            jComboBox_proveedor.addItem("Seleccione Proveedor:");

            while (rs.next()) {
                jComboBox_proveedor.addItem(rs.getString("nombre"));
            }

            cn.close();

        } catch (SQLException e) {
        }

    }

